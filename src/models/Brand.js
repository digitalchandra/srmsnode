const mongoose = require("mongoose");

const brandSchema = new mongoose.Schema(
  {
    tenantId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Tenant",
      required: true,
      index: true,
    },

    name: {
      type: String,
      required: true,
      trim: true,
    },

    description: {
      type: String,
      trim: true,
      default: "",
    },

    status: {
      type: String,
      enum: ["ACTIVE", "INACTIVE"],
      default: "ACTIVE",
    },
  },
  {
    timestamps: true,
  }
);

// Same brand name only once within a vendor
brandSchema.index(
  { tenantId: 1, name: 1 },
  { unique: true }
);

module.exports = mongoose.model("Brand", brandSchema);